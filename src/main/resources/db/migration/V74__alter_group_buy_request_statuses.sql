UPDATE group_buy_requests
SET status = CASE status
    WHEN 'SUBMITTED' THEN 'REQUEST_RECEIVED'
    WHEN 'IN_REVIEW' THEN 'IN_REVIEW'
    WHEN 'IN_CONTACT' THEN 'STORE_CONFIRMING'
    WHEN 'OPENED' THEN 'COMPLETED'
    WHEN 'REJECTED' THEN 'UNAVAILABLE'
    ELSE status
END;

UPDATE group_buy_request_status_histories
SET status = CASE status
    WHEN 'SUBMITTED' THEN 'REQUEST_RECEIVED'
    WHEN 'IN_REVIEW' THEN 'IN_REVIEW'
    WHEN 'IN_CONTACT' THEN 'STORE_CONFIRMING'
    WHEN 'OPENED' THEN 'COMPLETED'
    WHEN 'REJECTED' THEN 'UNAVAILABLE'
    ELSE status
END;

ALTER TABLE group_buy_requests
    MODIFY COLUMN status VARCHAR(20) NOT NULL DEFAULT 'REQUEST_RECEIVED';
